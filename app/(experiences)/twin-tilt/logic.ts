export function parseRoom(room: Room): Cell[][] {
  return room.rows.map((row) =>
    row.split("").map((char): Cell => {
      if (char === "#") return "wall";
      if (char === "~") return "sticky";
      if (char === "a") return "goalA";
      if (char === "b") return "goalB";
      return "empty";
    })
  );
}

export function slideBalls(cells: Cell[][], balls: Ball[], gravity: Dir): Ball[] {
  const { dx, dy } = VECTORS[gravity];
  const height = cells.length;
  const width = cells[0]?.length ?? 0;
  const blocked = (x: number, y: number, self: Ball): boolean => {
    if (x < 0 || y < 0 || x >= width || y >= height) return true;
    if (cells[y]?.[x] === "wall") return true;
    return balls.some((b) => b !== self && b.x === x && b.y === y);
  };
  const order = [...balls].sort((a, b) => b.x * dx + b.y * dy - (a.x * dx + a.y * dy));
  const moved = balls.map((b) => ({ ...b }));
  for (const ball of order) {
    const me = moved.find((b) => b.id === ball.id);
    if (!me) continue;
    for (;;) {
      const nx = me.x + dx;
      const ny = me.y + dy;
      if (blocked(nx, ny, me)) break;
      me.x = nx;
      me.y = ny;
      if (cells[ny]?.[nx] === "sticky") break;
    }
  }
  return moved;
}

/** Gravity starts pointing down; every move rotates the room and re-slides. */
export function initialSlide(room: Room): TiltState {
  const cells = parseRoom(room);
  return { gravity: "down", balls: slideBalls(cells, room.balls, "down") };
}

export function rotate(state: TiltState, cells: Cell[][], move: Move): TiltState {
  const gravity = move === "cw" ? CW_NEXT[state.gravity] : CCW_NEXT[state.gravity];
  return { gravity, balls: slideBalls(cells, state.balls, gravity) };
}

export function isWin(state: TiltState, cells: Cell[][]): boolean {
  return state.balls.every((ball) => {
    const cell = cells[ball.y]?.[ball.x];
    return ball.id === "A" ? cell === "goalA" : cell === "goalB";
  });
}

export function roomScore(moves: number, par: number): number {
  return Math.max(0, Math.min(100, 100 - 3 * (moves - par)));
}
