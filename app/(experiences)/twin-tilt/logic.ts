export type Dir = "up" | "right" | "down" | "left";
export type Move = "cw" | "ccw";
export type BallId = "A" | "B";
export type Ball = { id: BallId; x: number; y: number };
export type Cell = "empty" | "wall" | "sticky" | "goalA" | "goalB";

export type Room = {
  name: string;
  /** 6x6 rows: "." empty, "#" wall, "~" sticky, "a"/"b" goals. */
  rows: string[];
  balls: Ball[];
  par: number;
  solution: Move[];
};

export type TiltState = { gravity: Dir; balls: Ball[] };

const VECTORS: Record<Dir, { dx: number; dy: number }> = {
  up: { dx: 0, dy: -1 },
  right: { dx: 1, dy: 0 },
  down: { dx: 0, dy: 1 },
  left: { dx: -1, dy: 0 },
};
const CW_NEXT: Record<Dir, Dir> = { up: "right", right: "down", down: "left", left: "up" };
const CCW_NEXT: Record<Dir, Dir> = { up: "left", left: "down", down: "right", right: "up" };

