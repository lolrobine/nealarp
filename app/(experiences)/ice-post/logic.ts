/** Slide across the ice until something stops you: walls, the map edge, or the
 * postman — who takes one step along his patrol after every slide. Reach the postbox. */

export type Pt = { x: number; y: number };
export type SlideLevel = {
  name: string;
  rows: string[];
  start: Pt;
  goal: Pt;
  patrol: Pt[];
  par: number;
  /** Slide directions: 0 up, 1 right, 2 down, 3 left. */
  solution: number[];
};
export type SlideState = { x: number; y: number; pi: number };

const DIRS = [
  [0, -1],
  [1, 0],
  [0, 1],
  [-1, 0],
];

export function slide(level: SlideLevel, state: SlideState, dir: number): [number, number] {
  const [dx = 0, dy = 0] = DIRS[dir] ?? [0, 0];
  const postman = level.patrol[state.pi] ?? { x: -1, y: -1 };
  let cx = state.x;
  let cy = state.y;
  for (;;) {
    const nx = cx + dx;
    const ny = cy + dy;
    if (nx < 0 || ny < 0 || nx >= 6 || ny >= 6) break;
    if (level.rows[ny]?.[nx] === "#") break;
    if (nx === postman.x && ny === postman.y) break;
    cx = nx;
    cy = ny;
  }
  return [cx, cy];
}

export function initialState(level: SlideLevel): SlideState {
  return { x: level.start.x, y: level.start.y, pi: 0 };
}

export function applySlide(level: SlideLevel, state: SlideState, dir: number): SlideState {
  const [nx, ny] = slide(level, state, dir);
  if (nx === state.x && ny === state.y) return state;
  return { x: nx, y: ny, pi: (state.pi + 1) % level.patrol.length };
}

export function isWin(level: SlideLevel, state: SlideState): boolean {
  return state.x === level.goal.x && state.y === level.goal.y;
}

export function scoreRun(moves: number, par: number): number {
  return Math.max(0, Math.min(100, 100 - 4 * (moves - par)));
}

